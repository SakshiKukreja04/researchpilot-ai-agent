"""Data contracts and Pydantic v2 schemas for ResearchPilot.

Enforces strict validation, bounded list and string sizes, enumerated states,
and evidence provenance across the entire research lifecycle.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional
from urllib.parse import urlparse

from pydantic import BaseModel, ConfigDict, Field, field_validator


class ConfidenceLevel(str, Enum):
    """Rule-based confidence levels based on observable evidence."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class ExtractionStatus(str, Enum):
    """Status of page extraction."""

    SUCCESS = "success"
    EMPTY = "empty"
    FAILED = "failed"
    SKIPPED = "skipped"


class ResearchAnswerStatus(str, Enum):
    """Outcome status of research answer synthesis."""

    COMPLETED = "completed"
    PARTIAL = "partial"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    FAILED = "failed"


class WorkflowStage(str, Enum):
    """Explicit workflow states and run lifecycle."""

    RECEIVED = "RECEIVED"
    PLANNED = "PLANNED"
    SEARCHING = "SEARCHING"
    RETRIEVING = "RETRIEVING"
    FILTERING = "FILTERING"
    SYNTHESIZING = "SYNTHESIZING"
    VALIDATING = "VALIDATING"
    COMPLETED = "COMPLETED"
    DEGRADED = "DEGRADED"
    FAILED = "FAILED"


class ErrorCategory(str, Enum):
    """Normalized typed error categories."""

    TIMEOUT = "timeout"
    RATE_LIMIT = "rate_limit"
    AUTH_ERROR = "auth_error"
    CONNECTION_ERROR = "connection_error"
    VALIDATION_ERROR = "validation_error"
    EXTRACTION_ERROR = "extraction_error"
    BUDGET_EXHAUSTED = "budget_exhausted"
    UNSAFE_URL = "unsafe_url"
    UNKNOWN = "unknown"


# Permitted tools in the deterministic allowlist
ALLOWED_TOOLS = frozenset({"web_search", "fetch_and_extract"})


def _validate_http_url(v: str) -> str:
    """Ensure URL is non-empty and has http/https scheme."""
    v_clean = v.strip()
    if not v_clean:
        raise ValueError("URL cannot be empty")
    parsed = urlparse(v_clean)
    if parsed.scheme.lower() not in {"http", "https"}:
        raise ValueError(f"URL must have http or https scheme, got: {parsed.scheme or 'none'}")
    if not parsed.netloc:
        raise ValueError("URL must have a valid domain or network location")
    return v_clean


class ResearchRequest(BaseModel):
    """Incoming user request for research."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    question: str = Field(
        ...,
        min_length=3,
        max_length=1000,
        description="The primary research question or prompt.",
    )
    metadata: Optional[dict[str, Any]] = Field(
        default=None,
        description="Optional non-sensitive request metadata.",
    )

    @field_validator("question", mode="before")
    @classmethod
    def strip_and_validate_question(cls, v: Any) -> str:
        if not isinstance(v, str):
            raise ValueError("question must be a string")
        stripped = v.strip()
        if not stripped:
            raise ValueError("question cannot be empty or whitespace only")
        return stripped


class ResearchPlan(BaseModel):
    """Structured research plan generated by the planner."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    objective: str = Field(
        ...,
        min_length=5,
        max_length=500,
        description="Concise goal of the research inquiry.",
    )
    subquestions: list[str] = Field(
        ...,
        min_length=1,
        max_length=8,
        description="Decomposed subquestions guiding the search.",
    )
    search_queries: list[str] = Field(
        ...,
        min_length=1,
        max_length=10,
        description="Focused keyword queries for search tools.",
    )
    tools: list[str] = Field(
        ...,
        min_length=1,
        max_length=4,
        description="Allowlisted tools to execute.",
    )
    success_criteria: list[str] = Field(
        ...,
        min_length=1,
        max_length=8,
        description="Criteria determining whether evidence is sufficient.",
    )
    requires_fresh_evidence: bool = Field(
        default=False,
        description="Whether the plan requires recent or date-sensitive evidence.",
    )
    plan_notes: Optional[str] = Field(
        default=None,
        max_length=1000,
        description="Optional planner context, assumptions, or fallback notes.",
    )

    @field_validator("tools")
    @classmethod
    def validate_tool_allowlist(cls, tools: list[str]) -> list[str]:
        invalid = [t for t in tools if t not in ALLOWED_TOOLS]
        if invalid:
            raise ValueError(
                f"Disallowed tools requested: {invalid}. Permitted tools: {sorted(ALLOWED_TOOLS)}"
            )
        return tools

    @field_validator("subquestions", "search_queries", "success_criteria")
    @classmethod
    def validate_non_empty_items(cls, items: list[str]) -> list[str]:
        cleaned = []
        for idx, item in enumerate(items):
            if not isinstance(item, str) or not item.strip():
                raise ValueError(f"List item at index {idx} cannot be empty or whitespace")
            cleaned.append(item.strip())
        return cleaned


class SearchResult(BaseModel):
    """Single candidate page discovered via web search."""

    model_config = ConfigDict(frozen=True)

    title: str = Field(..., max_length=300)
    url: str = Field(..., max_length=2000)
    snippet: str = Field(..., max_length=3000)
    domain: Optional[str] = Field(default=None, max_length=255)
    published_date: Optional[str] = Field(default=None, max_length=64)

    @field_validator("url")
    @classmethod
    def validate_url(cls, v: str) -> str:
        return _validate_http_url(v)


class SourceDocument(BaseModel):
    """Extracted and normalized webpage evidence with quality provenance."""

    model_config = ConfigDict(frozen=True)

    source_id: str = Field(
        ...,
        pattern=r"^(S\d+|src_[a-f0-9]{8,64})$",
        description="Stable source identifier, e.g. S1 or deterministic src_<hash>.",
    )
    title: str = Field(..., max_length=300)
    url: str = Field(..., max_length=2000)
    domain: str = Field(..., max_length=255)
    content: str = Field(
        ...,
        max_length=50000,
        description="Main extracted text content.",
    )
    published_date: Optional[str] = Field(default=None, max_length=64)
    quality_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Heuristic quality score between 0.0 and 1.0.",
    )
    extraction_status: ExtractionStatus = ExtractionStatus.SUCCESS
    rejection_reason: Optional[str] = Field(default=None, max_length=300)

    @field_validator("url")
    @classmethod
    def validate_url(cls, v: str) -> str:
        return _validate_http_url(v)


class ClaimSupportStatus(str, Enum):
    """Claim verification status against cited excerpts."""

    SUPPORTED = "supported"
    PARTIALLY_SUPPORTED = "partially_supported"
    UNSUPPORTED = "unsupported"
    UNVERIFIED = "unverified"


class ClaimVerificationResult(BaseModel):
    """Result of evaluating a single claim against cited source evidence."""

    model_config = ConfigDict(frozen=True)

    claim: str
    status: ClaimSupportStatus
    explanation: str = Field(..., max_length=1000)


class AnswerEvaluation(BaseModel):
    """Deterministic evaluator report for citation and grounding quality."""

    citation_count: int = Field(default=0, ge=0)
    valid_citation_count: int = Field(default=0, ge=0)
    citation_validity_rate: float = Field(default=0.0, ge=0.0, le=1.0)
    grounded_finding_count: int = Field(default=0, ge=0)
    finding_count: int = Field(default=0, ge=0)
    grounding_rate: float = Field(default=0.0, ge=0.0, le=1.0)
    warnings: list[str] = Field(default_factory=list, max_length=20)
    guardrail_triggered: bool = False


class Finding(BaseModel):
    """Individual factual claim or conclusion grounded in retrieved sources."""

    model_config = ConfigDict(frozen=True)

    claim: str = Field(..., min_length=3, max_length=1000)
    explanation: Optional[str] = Field(default=None, max_length=3000)
    source_ids: list[str] = Field(
        default_factory=list,
        description="Stable IDs of retrieved sources supporting this claim (e.g. ['S1', 'src_a1b2c3d4e5f6']).",
    )
    support_status: Optional[ClaimSupportStatus] = Field(
        default=None,
        description="Verification status: supported, partially_supported, unsupported, or unverified.",
    )

    @field_validator("source_ids")
    @classmethod
    def validate_source_ids(cls, ids: list[str]) -> list[str]:
        # Validate format of source ids if present
        cleaned = []
        for s in ids:
            s_clean = s.strip()
            if s_clean:
                cleaned.append(s_clean)
        return cleaned


class ResearchAnswer(BaseModel):
    """Final synthesized research deliverable with visible provenance."""

    model_config = ConfigDict(frozen=True)

    user_question: str = Field(..., min_length=3, max_length=1000)
    short_answer: str = Field(..., min_length=5, max_length=4000)
    key_findings: list[Finding] = Field(default_factory=list, max_length=20)
    sources_used: list[str] = Field(default_factory=list, max_length=30)
    source_url_map: dict[str, str] = Field(
        default_factory=dict,
        description="Trusted mapping from stable source ID to verified retrieved URL.",
    )
    confidence: ConfidenceLevel = ConfidenceLevel.MEDIUM
    assumptions: list[str] = Field(default_factory=list, max_length=15)
    limitations: list[str] = Field(default_factory=list, max_length=15)
    suggested_next_steps: list[str] = Field(default_factory=list, max_length=15)
    status: ResearchAnswerStatus = ResearchAnswerStatus.COMPLETED


class ExecutionEvent(BaseModel):
    """Auditable runtime trace event for observability."""

    model_config = ConfigDict(frozen=True)

    run_id: str = Field(..., min_length=1, max_length=64)
    stage: WorkflowStage
    event_type: str = Field(..., min_length=1, max_length=64)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    duration_ms: Optional[float] = Field(default=None, ge=0.0)
    success: bool = True
    error_category: Optional[ErrorCategory] = None
    message: Optional[str] = Field(default=None, max_length=1000)


class CoverageReport(BaseModel):
    """Assessment of retrieved evidence against research plan subquestions."""

    model_config = ConfigDict(frozen=True)

    subquestion_coverage: dict[str, str] = Field(
        ...,
        description="Mapping from subquestion to 'supported', 'partially_supported', or 'unsupported'.",
    )
    supported_count: int = Field(default=0, ge=0)
    partially_supported_count: int = Field(default=0, ge=0)
    unsupported_count: int = Field(default=0, ge=0)
    coverage_ratio: float = Field(default=0.0, ge=0.0, le=1.0)
    missing_criteria: list[str] = Field(default_factory=list)
    unsupported_subquestions: list[str] = Field(default_factory=list)
    is_adequate: bool = False


class ResearchContext(BaseModel):
    """Container holding intermediate research evidence and execution trace."""

    model_config = ConfigDict(frozen=True)

    run_id: str
    request: ResearchRequest
    plan: ResearchPlan
    raw_search_results: list[SearchResult] = Field(default_factory=list)
    sources: list[SourceDocument] = Field(default_factory=list)
    rejected_sources: list[SourceDocument] = Field(default_factory=list)
    coverage: CoverageReport
    trace: list[ExecutionEvent] = Field(default_factory=list)
    status: ResearchAnswerStatus = ResearchAnswerStatus.COMPLETED
    answer: Optional[ResearchAnswer] = None
    quality_gate_warnings: list[str] = Field(default_factory=list)
    evaluation: Optional[AnswerEvaluation] = None
